def quiz_for(slug: str, order: int) -> dict:
    question, correct, wrong_a, wrong_b, explanation = QUIZZES[slug]
    answer = (order + 1) % 3
    options = [wrong_a, wrong_b]
    options.insert(answer, correct)
    return {"question": question, "options": options, "answer": answer, "explanation": explanation}
